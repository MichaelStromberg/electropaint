#!/usr/bin/env python3
"""Generate an IrisGL call tracer (eptrace.c) for IRIX 5.3, plus its opcode table.

Usage: gen_tracer.py PROTOS IMPORTS OUT_C OUT_JSON

PROTOS   flat prototypes (re/irix53/protos.txt, from gen_protos.py)
IMPORTS  names the target binary imports (one per line)

The tracer is preloaded with _RLD_LIST. Each wrapper logs one record and
forwards to the real function obtained with dlopen/dlsym. Records:
    u16 opcode, u16 payload length, payload (big-endian, native MIPS order)
Pointer args with known extents are logged by value (see EXTENTS); other
pointers are logged as their address. Return values are appended.
Nested calls (libgl calling its own exported entry points) are not logged.
"""
# The C templates use printf-style formatting; as f-strings every C brace
# would have to be doubled.
# ruff: noqa: UP031
import json
import re
import sys

# libm/libc functions we deliberately do NOT wrap (pure math, noise).
SKIP = {"atan2", "floor", "fmod", "hypot", "expm1"}
LIBC = {"time", "drand48", "srand48", "sginap"}

# Pointer arguments whose pointed-to data we log: name -> {argindex: count}
# count may be an int or "argN" meaning "value of argument N".
EXTENTS = {
    "v2f": {0: 2}, "v3f": {0: 3}, "n3f": {0: 3}, "t2f": {0: 2}, "c4f": {0: 4},
    "loadmatrix": {0: 16}, "multmatrix": {0: 16},
    "lmdef": {3: "arg2"}, "tevdef": {2: "arg1"}, "texdef2d": {},
}
# Out-parameters to log after the call: name -> list of (argindex, ctype)
OUTS = {
    "getsize": [(0, "long"), (1, "long")],
    "getorigin": [(0, "long"), (1, "long")],
}

CT = {  # normalized type -> (C type, logger)
    "char": ("char", "ept_u8"), "unsigned char": ("unsigned char", "ept_u8"),
    "short": ("short", "ept_u16"), "unsigned short": ("unsigned short", "ept_u16"),
    "int": ("int", "ept_u32"), "unsigned int": ("unsigned int", "ept_u32"),
    "long": ("long", "ept_u32"), "unsigned long": ("unsigned long", "ept_u32"),
    "float": ("float", "ept_f32"), "double": ("double", "ept_f64"),
}


def parse_protos(lines):
    """Flat prototypes ("ret name(type, type)") -> {name: (ret, [param types])}."""
    protos = {}
    for line in lines:
        line = line.strip()
        if not line or line.startswith("#"):
            continue
        m = re.match(r"^(.+?)\s*\b(\w+)\((.*)\)$", line)
        if m:
            protos[m.group(2)] = (m.group(1).strip(), [p.strip() for p in m.group(3).split(",")
                                                         if p.strip() not in ("", "void")])
    return protos


HEADER = r'''/*
 * eptrace.c -- GENERATED by tools/irix/gen_tracer.py. IrisGL call tracer for
 * IRIX 5.3, preloaded into ep with _RLD_LIST. Do not edit by hand.
 *
 * Environment:
 *   EPTRACE_OUT     trace file (default /usr/tmp/ep.trace)
 *   EPTRACE_FRAMES  stop (exit 0) after this many swapbuffers (default 300)
 *   EPTRACE_TIME    value returned by time() (default 12345)
 *   EPTRACE_PAUSE_AT, EPTRACE_PAUSE_SECS  hold the picture after that swap;
 *                   /usr/tmp/eptrace.paused exists while held
 */
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include <unistd.h>
#include <dlfcn.h>

static FILE *ept_fp;
static int ept_depth;
static long ept_frames, ept_maxframes = 300, ept_pause_at = -1, ept_pause_secs = 20;
static unsigned char ept_buf[4096];
static int ept_len;
static void *ept_gl, *ept_c;

static void ept_open(void)
{
	const char *p = getenv("EPTRACE_OUT"), *f = getenv("EPTRACE_FRAMES");
	ept_fp = fopen(p ? p : "/usr/tmp/ep.trace", "w");
	if (ept_fp == NULL) { perror("eptrace: fopen"); _exit(2); }
	if (f) ept_maxframes = atol(f);
	if ((f = getenv("EPTRACE_PAUSE_AT")) != NULL) ept_pause_at = atol(f);
	if ((f = getenv("EPTRACE_PAUSE_SECS")) != NULL) ept_pause_secs = atol(f);
	fwrite("EPT1", 1, 4, ept_fp);
}

static void *ept_sym(const char *name, int libc)
{
	void *h, *s;
	if (libc) {
		if (!ept_c) ept_c = dlopen("libc.so.1", RTLD_LAZY);
		h = ept_c;
	} else {
		if (!ept_gl) ept_gl = dlopen("libgl.so", RTLD_LAZY);
		h = ept_gl;
	}
	s = h ? dlsym(h, name) : NULL;
	if (s == NULL) { fprintf(stderr, "eptrace: no symbol %s\n", name); _exit(3); }
	return s;
}

static void ept_put(const void *p, int n)
{
	if (ept_len + n <= (int)sizeof(ept_buf)) { memcpy(ept_buf + ept_len, p, n); ept_len += n; }
}
static void ept_u8(unsigned long v) { unsigned char c = (unsigned char)v; ept_put(&c, 1); }
static void ept_u16(unsigned long v) { unsigned short s = (unsigned short)v; ept_put(&s, 2); }
static void ept_u32(unsigned long v) { ept_put(&v, 4); }
static void ept_f32(double v) { float f = (float)v; ept_put(&f, 4); }
static void ept_f64(double v) { ept_put(&v, 8); }
static void ept_fa(const float *p, long n) { if (p && n > 0 && n < 512) ept_put(p, (int)(n * 4)); }

static int ept_begin(int op)
{
	if (ept_depth++ > 0) return 0;
	if (ept_fp == NULL) ept_open();
	ept_len = 0;
	ept_u16(op);
	ept_u16(0);
	return 1;
}

static void ept_end(int logging)
{
	if (logging) {
		unsigned short plen = (unsigned short)(ept_len - 4);
		memcpy(ept_buf + 2, &plen, 2);
		fwrite(ept_buf, 1, ept_len, ept_fp);
	}
	ept_depth--;
}
'''


def generate(protos, imports):
    """The tracer's C source and its opcode table for the functions in
    `imports` that `protos` describes."""
    names = sorted(n for n in imports if n in protos and n not in SKIP)
    ops = {}
    out = [HEADER]
    for op, name in enumerate(names, start=1):
        wrap(out, ops, op, name, protos[name])
    return "\n".join(out), ops, names


def wrap(out, ops, op, name, proto):
    """Appends the wrapper for function `name` (opcode `op`) to `out`, and
    its entry to `ops`."""
    ret, params = proto
    varargs = "..." in params
    params = [p for p in params if p != "..."]
    ops[op] = {"name": name, "ret": ret, "params": params,
               "extents": {str(k): v for k, v in EXTENTS.get(name, {}).items()},
               "outs": OUTS.get(name, [])}
    if varargs:
        out.append("/* %s: varargs, not wrapped */\n" % name)
        return
    cparams = []
    for i, p in enumerate(params):
        base = p.rstrip(" *")
        if p.endswith("*"):
            cparams.append("%s a%d" % (p if base in CT or base == "void" else "void *", i))
        else:
            cparams.append("%s a%d" % (CT[p][0], i))
    sig = ", ".join(cparams) or "void"
    cret = ret if ret.endswith("*") else (CT[ret][0] if ret in CT else "void")
    fptr = "%s (*)(%s)" % (cret, ", ".join(cp.rsplit(" ", 1)[0] for cp in cparams) or "void")
    body = ["%s %s(%s)" % (cret, name, sig), "{"]
    if name != "time":
        body.append("\tstatic %s (*real)(%s);" % (cret, ", ".join(cp.rsplit(" ", 1)[0] for cp in cparams) or "void"))
    if ret != "void":
        body.append("\t%s r;" % cret)
    body.append("\tint lg;")
    if name == "time":
        body.append('\t{ const char *e = getenv("EPTRACE_TIME"); r = e ? atol(e) : 12345L; }')
        body.append("\tif (a0) *(long *)a0 = r;")
        body.append("\tlg = ept_begin(%d); ept_u32(r); ept_end(lg);" % op)
        body.append("\treturn r;")
        body.append("}")
        out.append("\n".join(body) + "\n")
        return
    body.append("\tif (!real) real = (%s)ept_sym(\"%s\", %d);" % (fptr, name, 1 if name in LIBC else 0))
    if name == "winopen":
        # IrisGL forks into the background in winopen; stay in the foreground
        # so the caller can wait, and flush so no record is written twice.
        body.append("\tif (ept_fp) fflush(ept_fp);")
        body.append("\t((void (*)(void))ept_sym(\"foreground\", 0))();")
    body.append("\tlg = ept_begin(%d);" % op)
    body.append("\tif (lg) {")
    for i, p in enumerate(params):
        ext = EXTENTS.get(name, {}).get(i)
        if ext is not None:
            cnt = ("a%s" % ext[3:]) if isinstance(ext, str) else str(ext)
            body.append("\t\tept_fa((const float *)a%d, (long)%s);" % (i, cnt))
        elif p.endswith("*"):
            body.append("\t\tept_u32((unsigned long)a%d);" % i)
        else:
            body.append("\t\t%s(a%d);" % (CT[p][1], i))
    body.append("\t}")
    call = "real(%s)" % ", ".join("a%d" % i for i in range(len(params)))
    if ret != "void":
        body.append("\tr = %s;" % call)
    else:
        body.append("\t%s;" % call)
    if lg_out := OUTS.get(name):
        for i, ctype in lg_out:
            body.append("\tif (lg && a%d) ept_u32((unsigned long)*(%s *)a%d);" % (i, ctype, i))
    if ret != "void":
        logger = "ept_u32((unsigned long)r)" if ret.endswith("*") else "%s(r)" % CT[ret][1]
        body.append("\tif (lg) %s;" % logger)
    body.append("\tept_end(lg);")
    if name == "swapbuffers":
        # EPTRACE_PAUSE_AT=N: hold the picture after swap N for
        # EPTRACE_PAUSE_SECS seconds (default 20), e.g. for scrsave.
        body.append("\tif (++ept_frames == ept_pause_at) {")
        body.append("\t\tFILE *m = fopen(\"/usr/tmp/eptrace.paused\", \"w\");")
        body.append("\t\tfflush(ept_fp);")
        body.append("\t\tif (m) fclose(m);")
        body.append("\t\tsleep(ept_pause_secs);")
        body.append("\t\tunlink(\"/usr/tmp/eptrace.paused\");")
        body.append("\t}")
        body.append("\tif (ept_frames >= ept_maxframes) { fflush(ept_fp); fclose(ept_fp); _exit(0); }")
    if ret != "void":
        body.append("\treturn r;")
    body.append("}")
    out.append("\n".join(body) + "\n")


def main(argv):
    if len(argv) != 5:
        sys.exit(__doc__)
    protos_path, imports_path, out_c, out_json = argv[1:5]
    with open(protos_path) as f:
        protos = parse_protos(f)
    with open(imports_path) as f:
        imports = set(f.read().split())
    c_text, ops, names = generate(protos, imports)
    with open(out_c, "w") as f:
        f.write(c_text)
    with open(out_json, "w") as f:
        json.dump({"magic": "EPT1", "ops": ops}, f, indent=1)
    print("wrapped %d functions -> %s" % (len(names), out_c))


if __name__ == "__main__":
    main(sys.argv)
